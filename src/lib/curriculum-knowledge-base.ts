/**
 * Helper function เพื่อค้นหาความรู้จากคลังหลักสูตรที่ตรงกับคำถามของนักเรียน
 */
export function searchCurriculumKnowledge(query: string, subject: string, moduleId: string): string {
  const subjectKnowledge = CURRICULUM_KNOWLEDGE_BASE[subject]
  if (!subjectKnowledge) return ''

  const currentModule = subjectKnowledge[moduleId]
  let resultContext = ''

  if (currentModule) {
    resultContext += `\n[หลักสูตร สพฐ. & มาตรฐานตัวชี้วัด]\n- ตัวชี้วัด: ${currentModule.obecIndicator}\n- นิยามวิชาการ: ${currentModule.academicDefinition}\n`
    resultContext += `\n[สูตร ทฤษฎี และกฎสำคัญ]\n- ${currentModule.coreFormulasAndTheorems.join('\n- ')}\n`
    resultContext += `\n[สูตรลัดและวิธีคิดเร็ว]\n- ${currentModule.speedHacks.join('\n- ')}\n`
    resultContext += `\n[จุดลวงที่ข้อสอบชอบหลอก]\n- ${currentModule.commonTrapAlerts.join('\n- ')}\n`
    resultContext += `\n[ข้อสอบแข่งขัน / ห้อง Gifted]\n- ${currentModule.giftedExamNotes.join('\n- ')}\n`
  }

  // Cross-module search in the same subject if query touches other topics
  const queryLower = query.toLowerCase()
  for (const [key, mod] of Object.entries(subjectKnowledge)) {
    if (key === moduleId) continue

    const isMatch = 
      mod.title.toLowerCase().includes(queryLower) ||
      mod.speedHacks.some(h => h.toLowerCase().includes(queryLower)) ||
      mod.coreFormulasAndTheorems.some(f => f.toLowerCase().includes(queryLower))

    if (isMatch) {
      resultContext += `\n[ข้อมูลเสริมที่เกี่ยวข้องจากเรื่อง: ${mod.title}]\n- ${mod.speedHacks.slice(0, 2).join('\n- ')}\n`
    }
  }

  return resultContext
}
