// Validate
let totalQuestions = 0;
const expectedModules = [
  'thai_reading',
  'thai_word_classes',
  'thai_royal_loanwords',
  'thai_sentence_structures',
  'thai_idioms_dialects',
  'thai_literature_poetry',
  'thai_writing',
  'thai_listening_speaking'
];

let errors = [];

expectedModules.forEach(mod => {
  if (!thaiQuizPool[mod]) {
    errors.push(`Missing module: ${mod}`);
    return;
  }
  const setB = thaiQuizPool[mod][0];
  if (!setB || setB.length !== 10) {
    errors.push(`Module ${mod} does not have exactly 10 questions (has ${setB ? setB.length : 0})`);
    return;
  }
  setB.forEach((q, idx) => {
    totalQuestions++;
    if (!q.id) errors.push(`${mod}[${idx}] missing id`);
    if (!q.question) errors.push(`${mod}[${idx}] missing question`);
    if (!Array.isArray(q.options) || q.options.length !== 4) errors.push(`${mod}[${idx}] options length != 4`);
    if (!q.options.includes(q.correctAnswer)) errors.push(`${mod}[${idx}] correctAnswer not in options! correctAnswer="${q.correctAnswer}"`);
    if (!q.explanation || !q.explanation.includes('วิเคราะห์ตัวเลือกที่ผิด')) errors.push(`${mod}[${idx}] missing Diagnostic explanation`);
    if (!q.tip) errors.push(`${mod}[${idx}] missing tip`);
  });
});

console.log('Validation results:');
console.log('Total modules:', Object.keys(thaiQuizPool).length);
console.log('Total questions in Set B:', totalQuestions);
if (errors.length > 0) {
  console.error('Errors found:', errors);
  process.exit(1);
} else {
  console.log('All 80 questions passed 100% validation check!');
}

